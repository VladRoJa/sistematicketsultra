"""Prepare a single-branch cobranza pilot from today's saved scheduler files.

This command only freezes an audience. It NEVER submits a provider request.
Run in the reports-scheduler container, where the generated XLSX files live.

Example:
  python -m app.warehouse.jobs.cobranza_iventas_pilot \
      --date 2026-11-11 --branch VILLAS_DEL_REY
"""
from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from app import create_app
from app.warehouse.jobs.cobranza_recurrente_rechazados_job import load_config
from app.warehouse.jobs.cobranza_iventas_preparation import (
    CobranzaCampaignPreparationError, prepare_cobranza_iventas_campaign,
)


def prepare_saved_pilot(*, business_date: date, branch_key: str) -> dict:
    # Files were generated by the existing Gasca scheduler, not reuploaded
    # by the operator or fetched from iVentas.
    base = load_config().output_base_dir / business_date.isoformat() / "sucursales"
    if not base.is_dir():
        raise CobranzaCampaignPreparationError(
            "No existen archivos diarios generados por la automatización."
        )
    paths = sorted(path for path in base.glob("*.xlsx") if path.is_file())
    if not paths:
        raise CobranzaCampaignPreparationError("El corte no contiene archivos XLSX por sucursal.")

    # We do not reconstruct a raw report or alter its original files.
    artifacts = [
        {"sucursal_raw": path.stem, "path": str(path)}
        for path in paths
    ]
    return prepare_cobranza_iventas_campaign(
        business_date=business_date, artifacts=artifacts,
        pilot_branch_key=branch_key,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Congelar piloto iVentas sin enviar WhatsApps.")
    parser.add_argument("--date", type=date.fromisoformat, required=True)
    parser.add_argument("--branch", required=True, help="Sucursal canónica, p. ej. VILLAS_DEL_REY")
    args = parser.parse_args()
    app = create_app()
    with app.app_context():
        result = prepare_saved_pilot(business_date=args.date, branch_key=args.branch)
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
