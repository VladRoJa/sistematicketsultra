def _grant(actor=None, role=None, effect="allow", scope="global",
           branch=None, branches=None, department=None, active=True,
           expires_at=None):
    assert (actor is None) != (role is None)
    with db.engine.begin() as con:
        con.execute(sa.text("""
            INSERT INTO permission_grants
            (principal_type, principal_user_id, principal_role_key, action_id,
             effect, scope_type, scope_branch_id, scope_branch_ids,
             scope_department_id, is_active, expires_at)
            VALUES (:type,:actor,:role,9,:effect,:scope,:branch,
                    CAST(:branches AS jsonb),:department,:active,:expires_at)
        """), {
            "type": "user" if actor is not None else "role",
            "actor": actor, "role": role, "effect": effect,
            "scope": scope, "branch": branch,
            "branches": json.dumps(branches) if branches is not None else None,
            "department": department, "active": active,
            "expires_at": expires_at,
        })


def _check(actor, branch=7, creator=501, kind="QUANTITY_DIFFERENCE"):
    return resolver_acceso_autorizacion_e3(
        actor_usuario_id=actor,
        solicitud_sucursal_id=branch,
        solicitud_creador_id=creator, tipo=kind,
    )


def test_e3_denegado_sin_grants_y_roles_no_liberados(env):
    assert _check(47).reason == "no_explicit_global_grant"
    assert _check(45, 1).reason == "no_explicit_scoped_grant"
    assert _check(91).reason == "no_explicit_scoped_grant"
    assert _check(55).reason == "role_not_enabled"
    assert _check(68).reason == "role_not_enabled"
    assert _check(999).reason == "actor_not_found"
    assert _check(True).reason == "invalid_request"


def test_e3_corporativo_solo_grant_individual_y_sin_autoaprobacion(env):
    _grant(role="ADMINISTRADOR")
    assert not _check(47).allowed
    assert not _check(48).allowed
    _grant(actor=47)
    assert _check(47, branch=7).allowed
    assert _check(47, branch=26, kind="MASTER_FIELD").global_scope
    assert _check(47, branch=7, creator=47).reason == "self_approval_forbidden"
    assert not _check(48).allowed  # Otro administrador no hereda grant de rol.
    _grant(actor=47, effect="deny", scope="branch", branch=7)
    assert _check(47, branch=7).reason == "explicit_deny"
    assert _check(47, branch=26).allowed


def test_e3_mantenimiento_interseccion_con_asignadas_y_maestro_global(env):
    _grant(role="MANTENIMIENTO", scope="global")
    assert _check(45, branch=1).allowed
    assert _check(45, branch=14).allowed
    assert _check(45, branch=7).reason == "branch_not_assigned"
    assert _check(45, branch=1, kind="MASTER_FIELD").reason == (
        "global_master_requires_corporate"
    )
    assert _check(45, branch=1, creator=45).reason == "self_approval_forbidden"
    _grant(actor=45, scope="branch", branch=14, effect="deny")
    assert _check(45, branch=14).reason == "explicit_deny"
    assert _check(45, branch=1).allowed


def test_e3_coordinacion_lista_de_grant_no_amplia_sucursal_real(env):
    _grant(actor=91, scope="branch_list", branches=[7, 8, 20])
    assert _check(91, 7).allowed
    assert _check(91, 8).allowed
    assert _check(91, 9).reason == "no_explicit_scoped_grant"
    assert _check(91, 20).reason == "branch_not_assigned"
    assert _check(91, 7, kind="MASTER_FIELD").reason == (
        "global_master_requires_corporate"
    )


def test_e3_denegado_para_regional_incluso_con_grant(env):
    _grant(actor=55)
    assert _check(55, 7).reason == "role_not_enabled"


def test_e3_grants_inactivos_expirados_y_catalogo_inactivo(env):
    _grant(actor=91, active=False)
    _grant(actor=91, expires_at="2020-01-01T00:00:00+00:00")
    assert _check(91, 7).reason == "no_explicit_scoped_grant"
    _grant(actor=91)
    assert _check(91, 7).allowed
    with db.engine.begin() as con:
        con.exec_driver_sql("UPDATE permission_actions SET is_active = false WHERE id = 9")
    assert _check(91, 7).reason == "no_explicit_scoped_grant"


def test_e3_rol_mantenimiento_no_suplanta_departamento_efectivo(env):
    """Un rol operativo y un grant no autorizan a cuentas de otro departamento."""
    _grant(role="MANTENIMIENTO", scope="global")
    _grant(actor=91, scope="branch", branch=7)
    _grant(actor=95, scope="branch", branch=7)

    assert _check(45, branch=1).allowed
    assert _check(91, branch=7).allowed
    assert _check(94, branch=1).reason == "department_not_enabled"
    assert _check(95, branch=7).reason == "department_not_enabled"
    assert alcance_revision_e3(94) is None
    assert alcance_revision_e3(95) is None
    assert alcance_revision_e3(45)["sucursales"] == [1, 14]
    assert alcance_revision_e3(91)["sucursales"] == [7]
