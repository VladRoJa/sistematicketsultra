"""QA E3: acción de autorización en catálogo, sin grants ni accesos implícitos."""
import importlib.util
import os
import secrets
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic.migration import MigrationContext
from alembic.operations import Operations

BASE = Path(__file__).resolve().parents[2]
PATH = (
    BASE / "migrations/versions/"
    "v2e3a1102626_inventory_correction_approve_action.py"
)
spec = importlib.util.spec_from_file_location("inventario_e3_permission_action", PATH)
migration = importlib.util.module_from_spec(spec)
assert spec and spec.loader
spec.loader.exec_module(migration)


def test_e3_accion_solo_catalogo_y_encadena_revision():
    assert migration.revision == "v2e3a1102626"
    assert migration.down_revision == "v2e3p2102626"
    assert migration.ACTION == "inventory.correction_approve"


def test_e3_postgres_action_sin_grants_y_downgrade_protegido(monkeypatch):
    url = os.environ.get("INVENTARIO_E2_TEST_POSTGRES_URL")
    if not url:
        pytest.skip("Requiere PostgreSQL efímero para QA E3")

    schema = "inv_v2_e3_perm_" + secrets.token_hex(5)
    engine = sa.create_engine(url, future=True)
    try:
        with engine.begin() as con:
            con.exec_driver_sql(f"CREATE SCHEMA {schema}")
            con.exec_driver_sql(f"SET search_path TO {schema}")
            con.exec_driver_sql("""
                CREATE TABLE permission_modules (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    key VARCHAR(120) UNIQUE NOT NULL,
                    is_active BOOLEAN NOT NULL DEFAULT true,
                    base_action_id INTEGER
                )
            """)
            con.exec_driver_sql("""
                CREATE TABLE permission_actions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    module_id INTEGER NOT NULL REFERENCES permission_modules(id),
                    key VARCHAR(120) NOT NULL,
                    full_key VARCHAR(240) UNIQUE NOT NULL,
                    name VARCHAR(180) NOT NULL,
                    description TEXT,
                    risk_level VARCHAR(40) NOT NULL,
                    is_active BOOLEAN NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                    UNIQUE(module_id, key)
                )
            """)
            con.exec_driver_sql("""
                CREATE TABLE permission_grants (
                    id INTEGER PRIMARY KEY,
                    action_id INTEGER REFERENCES permission_actions(id)
                )
            """)
            con.exec_driver_sql("""
                CREATE TABLE permission_route_map (
                    id INTEGER PRIMARY KEY,
                    action_id INTEGER REFERENCES permission_actions(id)
                )
            """)
            con.exec_driver_sql("""
                INSERT INTO permission_modules (id,key) VALUES (2,'inventory')
            """)
            con.exec_driver_sql("""
                INSERT INTO permission_actions
                    (module_id,key,full_key,name,risk_level,is_active)
                VALUES (2,'read','inventory.read','Consultar','low',true)
            """)

            monkeypatch.setattr(migration, "op",
                                Operations(MigrationContext.configure(con)))
            migration.upgrade()

            action = con.execute(sa.text("""
                SELECT id,module_id,key,risk_level,is_active
                FROM permission_actions
                WHERE full_key = 'inventory.correction_approve'
            """)).one()
            assert action.module_id == 2
            assert action.key == "correction_approve"
            assert action.risk_level == "critical"
            assert action.is_active is True
            assert con.exec_driver_sql(
                "SELECT count(*) FROM permission_grants"
            ).scalar_one() == 0
            assert con.exec_driver_sql(
                "SELECT count(*) FROM permission_actions"
            ).scalar_one() == 2

            # No sobreescribir una acción que ya existe por otro origen.
            with pytest.raises(RuntimeError, match="ya existe"):
                migration.upgrade()

            # Un permiso futuro impide retirar una acción en uso.
            con.execute(sa.text(
                "INSERT INTO permission_grants(id,action_id) VALUES (1,:id)"
            ), {"id": action.id})
            with pytest.raises(RuntimeError, match="referenciada"):
                migration.downgrade()
            con.exec_driver_sql("DELETE FROM permission_grants")

            # Un mapeo futuro de rutas también debe proteger la migración.
            con.execute(sa.text(
                "INSERT INTO permission_route_map(id,action_id) VALUES (1,:id)"
            ), {"id": action.id})
            with pytest.raises(RuntimeError, match="referenciada"):
                migration.downgrade()
            con.exec_driver_sql("DELETE FROM permission_route_map")

            migration.downgrade()
            assert con.exec_driver_sql("""
                SELECT count(*) FROM permission_actions
                WHERE full_key = 'inventory.correction_approve'
            """).scalar_one() == 0
            assert con.exec_driver_sql("""
                SELECT count(*) FROM permission_actions
                WHERE full_key = 'inventory.read'
            """).scalar_one() == 1
    finally:
        with engine.begin() as con:
            con.exec_driver_sql(f"DROP SCHEMA IF EXISTS {schema} CASCADE")
        engine.dispose()
