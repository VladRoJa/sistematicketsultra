def test_e2_revision_continua_cadena_y_no_crea_heads_paralelos():
    assert migration.revision == "v2e2a7c92623"
    assert migration.down_revision == "l23c10202623"
    cfg = AlembicConfig()
    cfg.set_main_option("script_location", str(BASE / "migrations"))
    graph = ScriptDirectory.from_config(cfg)
    assert graph.get_heads() == ["v2e2a7c92623"]


def test_e2_modela_solo_solicitudes_con_fk_compuesta_e_idempotencia():
    table = InventarioSolicitudCorreccionORM.__table__
    assert table.name == "inventario_correccion_solicitudes"
    assert {"tipo", "estado", "sucursal_id", "inventario_id",
            "baseline_canonico", "creado_por_usuario_id", "creado_en_utc",
            "idempotency_key", "request_fingerprint"} <= set(table.c.keys())
    assert isinstance(table.c.baseline_canonico.type, JSONB)
    assert isinstance(table.c.idempotency_key.type, UUID)
    assert table.c.creado_en_utc.type.timezone
    fks = {
        constraint.name: constraint
        for constraint in table.constraints
        if isinstance(constraint, sa.ForeignKeyConstraint)
    }
    assert (
        [element.target_fullname for element in
         fks["fk_inv_corr_solicitudes_stock_sucursal"].elements]
        == ["inventario_sucursal.inventario_id", "inventario_sucursal.sucursal_id"]
    )
    assert all(fk.ondelete == "RESTRICT" for fk in fks.values())
    indexes = {index.name for index in table.indexes}
    assert "ix_inv_corr_solicitudes_sucursal_estado_fecha" in indexes
    assert "ix_inv_corr_solicitudes_inventario_estado" in indexes
    assert "ix_inv_corr_solicitudes_creador_fecha" in indexes


def test_e2_upgrade_no_ejecuta_dml_ni_altera_tablas_v1(monkeypatch):
    created = []
    indexes = []

    class Recorder:
        def create_table(self, name, *args):
            created.append(name)

        def create_index(self, name, table_name, columns):
            indexes.append((name, table_name, tuple(columns)))

    monkeypatch.setattr(migration, "op", Recorder())
    migration.upgrade()
    assert created == ["inventario_correccion_solicitudes"]
    assert len(indexes) == 3
    assert {name for name, _, _ in indexes} == {
        "ix_inv_corr_solicitudes_sucursal_estado_fecha",
        "ix_inv_corr_solicitudes_inventario_estado",
        "ix_inv_corr_solicitudes_creador_fecha",
    }


def test_e2_postgres_fk_scope_idempotencia_checks_y_downgrade(monkeypatch):
    url = os.getenv("INVENTARIO_E2_TEST_POSTGRES_URL")
    if not url:
        pytest.skip("PostgreSQL temporal requerido para QA de restricciones")

    schema = "inv_v2_e2_" + secrets.token_hex(5)
    engine = sa.create_engine(url, future=True)
    try:
        with engine.begin() as con:
            con.exec_driver_sql(f"CREATE SCHEMA {schema}")
            con.exec_driver_sql(f"SET search_path TO {schema}")
            con.exec_driver_sql("CREATE TABLE users (id INTEGER PRIMARY KEY)")
            con.exec_driver_sql(
                "CREATE TABLE sucursales (sucursal_id INTEGER PRIMARY KEY)"
            )
            con.exec_driver_sql(
                "CREATE TABLE inventario_general (id INTEGER PRIMARY KEY)"
            )
            con.exec_driver_sql(
                "CREATE TABLE inventario_sucursal ("
                "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "inventario_id INTEGER NOT NULL REFERENCES inventario_general(id), "
                "sucursal_id INTEGER NOT NULL REFERENCES sucursales(sucursal_id), "
                "CONSTRAINT uq_inventario_sucursal_activo UNIQUE (inventario_id, sucursal_id))"
            )
            monkeypatch.setattr(
                migration, "op", Operations(MigrationContext.configure(con))
            )
            migration.upgrade()
            inspector = sa.inspect(con)
            assert inspector.has_table("inventario_correccion_solicitudes")
            indexes = inspector.get_indexes("inventario_correccion_solicitudes")
            assert {
                "ix_inv_corr_solicitudes_sucursal_estado_fecha",
                "ix_inv_corr_solicitudes_inventario_estado",
                "ix_inv_corr_solicitudes_creador_fecha",
            } <= {index["name"] for index in indexes}
            # PostgreSQL refleja tambien el indice de la UNIQUE.
            assert any(
                index.get("duplicates_constraint") ==
                "uq_inv_corr_solicitudes_actor_idempotencia"
                for index in indexes
            )

            con.exec_driver_sql("INSERT INTO users (id) VALUES (51)")
            con.exec_driver_sql(
                "INSERT INTO sucursales (sucursal_id) VALUES (7), (8)"
            )
            con.exec_driver_sql("INSERT INTO inventario_general (id) VALUES (501)")
            con.exec_driver_sql(
                "INSERT INTO inventario_sucursal (inventario_id, sucursal_id) "
                "VALUES (501, 7)"
            )
            insert_stmt = sa.text("""
                INSERT INTO inventario_correccion_solicitudes
                (tipo, sucursal_id, inventario_id, valor_original,
                 valor_propuesto, baseline_canonico, motivo,
                 creado_por_usuario_id, idempotency_key, request_fingerprint)
                VALUES ('QUANTITY_DIFFERENCE', :branch, 501,
                    CAST(:original AS jsonb), CAST(:proposed AS jsonb),
                    CAST(:baseline AS jsonb), 'Conteo físico de prueba',
                    51, CAST(:request_key AS uuid), :fingerprint)
            """)
            con.execute(insert_stmt, {
                "branch": 7,
                "request_key": "11111111-1111-4111-8111-111111111111",
                "fingerprint": "a" * 64,
                "original": '{"stock":1}',
                "proposed": '{"cantidad_fisica":2}',
                "baseline": '{"stock":1}',
            })
            saved = con.execute(sa.text(
                "SELECT estado, sucursal_id, inventario_id "
                "FROM inventario_correccion_solicitudes"
            )).one()
            assert saved == ("PENDING", 7, 501)

            # Un segundo intento con la misma clave nunca genera otra fila.
            with pytest.raises(sa.exc.IntegrityError):
                with con.begin_nested():
                    con.execute(insert_stmt, {
                        "branch": 7,
                        "request_key": "11111111-1111-4111-8111-111111111111",
                        "fingerprint": "a" * 64,
                        "original": '{"stock":1}',
                        "proposed": '{"cantidad_fisica":2}',
                        "baseline": '{"stock":1}',
                    })

            # La sucursal 8 existe, pero la referencia 501 NO está asignada allí.
            with pytest.raises(sa.exc.IntegrityError):
                with con.begin_nested():
                    con.execute(insert_stmt, {
                        "branch": 8,
                        "request_key": "22222222-2222-4222-8222-222222222222",
                        "fingerprint": "b" * 64,
                        "original": '{"stock":1}',
                        "proposed": '{"cantidad_fisica":2}',
                        "baseline": '{"stock":1}',
                    })

            # Hallazgo sin inventario_id: permitido con referencia provisional.
            con.exec_driver_sql("""
                INSERT INTO inventario_correccion_solicitudes
                (tipo, sucursal_id, inventario_id, hallazgo_provisional,
                 baseline_canonico, motivo, creado_por_usuario_id,
                 idempotency_key, request_fingerprint)
                VALUES ('UNREGISTERED_FIND', 8, NULL, '{"nombre":"Caminadora"}'::jsonb,
                    '{}'::jsonb, 'Hallazgo físico de prueba', 51,
                    '33333333-3333-4333-8333-333333333333', 'cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc')
            """)
            assert con.execute(sa.text(
                "SELECT count(*) FROM inventario_correccion_solicitudes"
            )).scalar_one() == 2
            assert con.execute(sa.text(
                "SELECT COUNT(*) FROM inventario_sucursal WHERE inventario_id=501 AND sucursal_id=7"
            )).scalar_one() == 1

            with pytest.raises(RuntimeError, match="existen solicitudes"):
                migration.downgrade()

            con.exec_driver_sql(
                "DELETE FROM inventario_correccion_solicitudes"
            )
            migration.downgrade()
            assert not sa.inspect(con).has_table("inventario_correccion_solicitudes")
            assert con.execute(sa.text(
                "SELECT count(*) FROM inventario_sucursal"
            )).scalar_one() == 1
    finally:
        with engine.begin() as cleanup:
            cleanup.exec_driver_sql(f"DROP SCHEMA IF EXISTS {schema} CASCADE")
        engine.dispose()
