def _stage(ctx, **overrides):
    args = {
        "warehouse_upload_id": CANDIDATE_UPLOAD_ID,
        "canonical_snapshot_id": ctx["baseline_id"],
        "business_date": BUSINESS_DATE,
    }
    args.update(overrides)
    return stage_kpi_desempeno_upload(**args)


def test_pg_stage_is_noncanonical_and_preserves_original_and_no_track(pg_synthetic):
    result = _stage(pg_synthetic)
    assert result["status"] == "staged"
    assert result["is_canonical"] is False
    assert result["was_idempotent"] is False
    assert result["changed_branches"] == 1
    assert result["changed_fields"] == 1
    assert result["canonical_snapshot_id"] == pg_synthetic["baseline_id"]

    snaps = KpiDesempenoSnapshotORM.query.order_by(KpiDesempenoSnapshotORM.id).all()
    assert len(snaps) == 2
    assert snaps[0].id == pg_synthetic["baseline_id"]
    assert snaps[0].is_canonical is True
    assert snaps[0].warehouse_upload_id == CANONICAL_UPLOAD_ID
    assert snaps[1].id == result["snapshot_id"]
    assert snaps[1].is_canonical is False
    assert snaps[1].warehouse_upload_id == CANDIDATE_UPLOAD_ID
    assert KpiDesempenoSnapshotRowORM.query.filter_by(snapshot_id=snaps[1].id).count() == 2
    assert KpiDesempenoSnapshotRowORM.query.filter_by(snapshot_id=snaps[0].id).first().reactivaciones == 40
    assert KpiDesempenoSnapshotRowORM.query.filter_by(snapshot_id=snaps[1].id).first().reactivaciones == 29
    assert not sa.inspect(db.engine).has_table("track_daily_mart")
    assert not sa.inspect(db.engine).has_table("track_source_desempeno_daily")


def test_pg_idempotency_reuses_only_the_noncanonical_upload(pg_synthetic):
    first = _stage(pg_synthetic)
    second = _stage(pg_synthetic)
    assert second["status"] == "already_staged"
    assert second["was_idempotent"] is True
    assert first["snapshot_id"] == second["snapshot_id"]
    assert KpiDesempenoSnapshotORM.query.count() == 2


