def _data(*, reactivaciones=40, second_branch="NORTE", bad_integer=None):
    first = ["CENTRO", 110, 25, reactivaciones, 8, 7, 168, 200, 0.84]
    if bad_integer is not None:
        first[3] = bad_integer
    second = [second_branch, 120, 19, 32, 9, 8, 163, 210, 0.78]
    return [first, second]


def _xlsx(*, reactivaciones=40, second_branch="NORTE",
          embedded_date=BUSINESS_DATE, bad_integer=None):
    result = BytesIO()
    with pd.ExcelWriter(result, engine="openpyxl") as writer:
        pd.DataFrame(
            _data(reactivaciones=reactivaciones, second_branch=second_branch,
                  bad_integer=bad_integer),
            columns=EXPECTED_KPI_DESEMPENO_COLUMNS,
        ).to_excel(writer, sheet_name="data", index=False)
        if embedded_date is not None:
            pd.DataFrame([
                {"key": "report_type", "value": "kpi_desempeno"},
                {"key": "business_date", "value": str(embedded_date)},
            ]).to_excel(writer, sheet_name="metadata", index=False)
    return result.getvalue()


