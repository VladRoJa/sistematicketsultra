@pytest.mark.parametrize("case", ["no_change", "new_branch", "wrong_date", "fraction", "metadata_date"])
def test_pg_invalid_candidate_cannot_stage(pg_synthetic, case):
    candidate_id = 709
    payload = {
        "no_change": _xlsx(),
        "new_branch": _xlsx(second_branch="OTRA"),
        "wrong_date": _xlsx(reactivaciones=22),
        "fraction": _xlsx(reactivaciones=22, bad_integer=21.25),
        "metadata_date": _xlsx(reactivaciones=22, embedded_date=date(2026, 8, 18)),
    }[case]
    cutoff = date(2026, 8, 18) if case == "wrong_date" else BUSINESS_DATE
    pg_synthetic["create_upload"](candidate_id, payload, cutoff=cutoff)
    with pytest.raises(KpiDesempenoStagingError):
        _stage(pg_synthetic, warehouse_upload_id=candidate_id)
    assert KpiDesempenoSnapshotORM.query.count() == 1
    assert KpiDesempenoSnapshotORM.query.filter_by(is_canonical=True).one().id == pg_synthetic["baseline_id"]


