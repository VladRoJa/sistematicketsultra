def _payload(ids, decision="APPROVED", key=None, reason="Revisión oficial con evidencia"):
    return {
        "solicitud_ids":ids,
        "decision":decision,"motivo":reason,
        "idempotency_key":key or str(uuid4()),
    }


def _post(env, user, payload):
    app, heads = env
    return app.test_client().post(
        "/api/inventario/solicitudes/decisiones/lote",
        headers=heads[user], json=payload,
    )


def _sql(query,params=None):
    return db.session.execute(sa.text(query),params or {}).scalar_one()


