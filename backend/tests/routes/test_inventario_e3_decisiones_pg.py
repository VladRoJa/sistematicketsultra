def test_e3_segunda_aprobacion_concurrente_aplica_una_sola_vez(env):
    _grant(45)
    _grant(47)
    req = _request()
    # Cada thread tiene su propio test_client y contexto Flask.
    def decide(user):
        with env[0].app_context():
            return _post(env,user,_payload([req])).status_code

    with ThreadPoolExecutor(max_workers=2) as ex:
        statuses = list(ex.map(decide,[45,47]))
    assert sorted(statuses) == [201,409],statuses
    db.session.remove()
    assert _sql("SELECT count(*) FROM inventario_correccion_ajustes") == 1
    assert _sql("SELECT stock FROM inventario_sucursal WHERE inventario_id=501 AND sucursal_id=7") == 2


