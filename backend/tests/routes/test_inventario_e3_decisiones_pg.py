def _grant(actor, scope="global", branch=None, effect="allow"):
    with db.engine.begin() as con:
        con.execute(sa.text("""
            INSERT INTO permission_grants
            (principal_type,principal_user_id,action_id,effect,scope_type,
             scope_branch_id,is_active)
            VALUES('user',:actor,9,:effect,:scope,:branch,true)
        """), {"actor":actor,"effect":effect,"scope":scope,"branch":branch})


def _request(kind="QUANTITY_DIFFERENCE", inv=501, branch=7, creator=98,
             proposed=None, original=None, field=None, baseline=None):
    stock = 3 if inv == 501 else 1
    if proposed is None:
        proposed = {"cantidad_fisica":2} if kind == "QUANTITY_DIFFERENCE" else (
            "Remo nuevo" if kind == "MASTER_FIELD" else
            {"no_localizado":True} if kind == "NOT_LOCATED" else None
        )
    if original is None:
        original = {"stock":stock} if kind != "MASTER_FIELD" else "Remo"
    if baseline is None:
        baseline = {"inventario_id":inv,"sucursal_id":branch,"stock":stock}
        if kind == "MASTER_FIELD":
            baseline.update({"campo":field or "nombre","valor":original})
    row = InventarioSolicitudCorreccionORM(
        tipo=kind, estado="PENDING", sucursal_id=branch, inventario_id=inv,
        campo=field if kind == "MASTER_FIELD" else None,
        valor_original=original if kind != "UNREGISTERED_FIND" else None,
        valor_propuesto=proposed if kind != "UNREGISTERED_FIND" else None,
        hallazgo_provisional={"nombre":"Bicicleta","tipo":"APARATOS"} if kind == "UNREGISTERED_FIND" else None,
        baseline_canonico=baseline,
        motivo="Conteo auditado con evidencia real",
        evidencia_descriptiva=(
            "Revisión física de ubicaciones, código y conteo total"
            if kind in ("NOT_LOCATED", "UNREGISTERED_FIND") else None
        ),
        fecha_observacion_local=(
            date(2026, 10, 26)
            if kind in ("NOT_LOCATED", "UNREGISTERED_FIND") else None
        ),
        creado_por_usuario_id=creator,
        idempotency_key=uuid4(), request_fingerprint="a" * 64,
    )
    if kind == "UNREGISTERED_FIND":
        row.inventario_id = None
        row.baseline_canonico = {"inventario_id":None,"sucursal_id":branch}
    db.session.add(row)
    db.session.commit()
    return row.id


