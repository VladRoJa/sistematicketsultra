def test_falsificacion_validacion_y_concurrencia_detectable(api):
    before = _snapshot(api)
    for field, value in (
        ("estado", "APPROVED"),
        ("creado_por_usuario_id", 2),
        ("baseline_canonico", {"stock": 999}),
        ("stock", -999),
    ):
        forged = _payload()
        forged[field] = value
        assert _post(api, forged).status_code == 400

    stale = _payload()
    stale["valor_original"] = {"stock": 999}
    assert _post(api, stale).status_code == 409
    different_branch = _payload(branch=8)
    assert _post(api, different_branch).status_code == 404
    malformed = _payload()
    malformed["valor_propuesto"] = {"cantidad_fisica": True}
    assert _post(api, malformed).status_code == 400
    # Ausencia física total no debe saltarse el gate de evidencia NOT_LOCATED.
    zero = _payload()
    zero["valor_propuesto"] = {"cantidad_fisica": 0}
    denied = _post(api, zero)
    assert denied.status_code == 400, denied.get_json()
    assert "NOT_LOCATED" in denied.get_json()["detail"]
    untrusted = _payload()
    untrusted["tipo"] = []
    assert _post(api, untrusted).status_code == 400
    assert _snapshot(api) == before


