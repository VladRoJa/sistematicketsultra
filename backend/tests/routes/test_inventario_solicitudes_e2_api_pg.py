def _payload(kind="QUANTITY_DIFFERENCE", branch=7, inventory=501):
    data = {
        "tipo": kind,
        "sucursal_id": branch,
        "inventario_id": inventory,
        "motivo": "Comprobación física del inventario para E2",
        "idempotency_key": str(uuid4()),
    }
    if kind == "MASTER_FIELD":
        data.update(
            campo="nombre", valor_original="Caminadora",
            valor_propuesto="Caminadora modelo X",
        )
    elif kind == "QUANTITY_DIFFERENCE":
        data.update(valor_original={"stock": 3},
                    valor_propuesto={"cantidad_fisica": 2})
    elif kind == "NOT_LOCATED":
        data.update(valor_original={"stock": 3},
                    valor_propuesto={"no_localizado": True})
    elif kind == "UNREGISTERED_FIND":
        data.pop("inventario_id")
        data.update(hallazgo_provisional={
            "nombre": "Bicicleta sin etiqueta", "tipo": "APARATOS"
        })
    if kind in ("NOT_LOCATED", "UNREGISTERED_FIND"):
        data["fecha_observacion_local"] = "2026-10-26"
        data["evidencia_descriptiva"] = (
            "Recorrido físico de sucursal y revisión de referencias y ubicaciones"
        )
    return data


def _post(api, data, user_id=1):
    client, tokens, _ = api
    return client.post("/api/inventario/solicitudes",
                       headers=tokens[user_id], json=data)


def _snapshot(api):
    _, _, app = api
    with app.app_context():
        stocks = db.session.execute(
            sa.text("SELECT inventario_id,sucursal_id,stock "
                    "FROM inventario_sucursal ORDER BY inventario_id")
        ).all()
        names = db.session.execute(
            sa.text("SELECT id,nombre FROM inventario_general ORDER BY id")
        ).all()
        return list(stocks), list(names)


def test_jwt_y_roles_prohibidos_sin_fuga(api):
    client, tokens, _ = api
    assert client.get("/api/inventario/solicitudes").status_code == 401
    for user_id in (4, 5, 6, 8):
        assert client.get("/api/inventario/solicitudes", headers=tokens[user_id]).status_code == 403
        assert client.get("/api/inventario/solicitudes/1", headers=tokens[user_id]).status_code == 403
        assert _post(api, _payload(), user_id=user_id).status_code == 403
    assert client.get("/api/inventario/solicitudes", headers=tokens[999]).status_code == 401


def test_stock_diferente_es_solo_propuesta_y_reintento_idempotente(api):
    before = _snapshot(api)
    payload = _payload()
    made = _post(api, payload)
    assert made.status_code == 201, made.get_json()
    data = made.get_json()["solicitud"]
    assert data["estado"] == "PENDING"
    assert data["valor_original"] == {"stock": 3}
    assert data["valor_propuesto"] == {"cantidad_fisica": 2}
    assert data["baseline_canonico"]["stock"] == 3
    assert data["creado_por_usuario_id"] == 1
    assert "idempotency_key" not in data
    assert _snapshot(api) == before

    again = _post(api, payload)
    assert again.status_code == 200, again.get_json()
    assert again.get_json()["replayed"] is True
    assert again.get_json()["solicitud"]["id"] == data["id"]

    changed = deepcopy(payload)
    changed["motivo"] = "Segundo motivo para la misma llave de solicitud"
    assert _post(api, changed).status_code == 409
    assert _snapshot(api) == before


def test_maestro_confirma_baseline_y_mantiene_nombre_oficial(api):
    before = _snapshot(api)
    stale = _payload("MASTER_FIELD")
    stale["valor_original"] = "Nombre antiguo"
